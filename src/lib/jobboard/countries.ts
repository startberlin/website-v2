const countryNames = new Map(countries.map((country) => [country.code, country.name]));
const normaliseSearch = (value: string) =>
	value.normalize('NFD').replace(/\p{Diacritic}/gu, '').toLowerCase().trim();
const searchableCountries = countries.map((country) => ({
	country,
	search: normaliseSearch([country.name, country.code, ...(country.aliases ?? [])].join(' ')),
}));

export function getCountryName(code: string): string {
	return countryNames.get(code) ?? code;
}

export function filterCountries(query: string): readonly Country[] {
	const search = normaliseSearch(query);
	if (!search) return countries;
	return searchableCountries.filter((entry) => entry.search.includes(search)).map((entry) => entry.country);
}
